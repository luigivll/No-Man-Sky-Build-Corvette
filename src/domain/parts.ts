import type { DesignStyle, PartCategory, PartClass, PartDef, PartFinish, SnapNode, Vec3 } from "./types";
import { allNodes, type NodeOptions } from "./snap-nodes";
import { vec } from "./vec";

/**
 * Corvette module catalogue.
 *
 * Names, categories, classes and workshop prices follow the live Corvette
 * Workshop terminal (No Man's Sky "Voyagers" 6.x). The `sceneId` values follow
 * the in-game scene-node naming convention used by the ship parts
 * (`BIG_COK1X2_A`, `BIG_TRU1X1_C`, ...) — they drive both the extracted-mesh
 * loader in `src/three/ModelRegistry.ts` and the NMS Save Editor exporter.
 *
 * Stats are engineering approximations used by the shipyard's own telemetry
 * read-out; the game re-rolls real part stats per save/character.
 */

interface PartDraft {
  id: string;
  name: string;
  category: PartCategory;
  style: DesignStyle;
  archetype: string;
  size: Vec3;
  sceneId: string;
  class: PartClass;
  acquisition: "starter" | "trade" | "salvage";
  price: number | null;
  mass: number;
  power?: number;
  shield?: number;
  weapon?: number;
  cargoSlots?: number;
  speed?: number;
  manoeuvre?: number;
  boost?: number;
  tags: readonly string[];
  finish?: PartFinish;
  blurb?: string;
  nodes?: NodeOptions;
}

function definePart(draft: PartDraft): PartDef {
  const nodes: readonly SnapNode[] = allNodes(draft.size, draft.nodes ?? {});

  return {
    id: draft.id,
    name: draft.name,
    category: draft.category,
    style: draft.style,
    archetype: draft.archetype,
    size: draft.size,
    sceneId: draft.sceneId,
    itemId: draft.sceneId,
    class: draft.class,
    acquisition: draft.acquisition,
    price: draft.price,
    mass: draft.mass,
    power: draft.power ?? 0,
    shield: draft.shield ?? 0,
    weapon: draft.weapon ?? 0,
    cargoSlots: draft.cargoSlots ?? 0,
    speed: draft.speed ?? 0,
    manoeuvre: draft.manoeuvre ?? 0,
    boost: draft.boost ?? 0,
    tags: draft.tags,
    nodes,
    finish: draft.finish,
    blurb: draft.blurb,
  };
}

