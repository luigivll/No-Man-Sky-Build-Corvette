export const getPart = (id: string): PartDef => {
  const part = PART_BY_ID.get(id);
  if (!part) throw new Error(`Unknown corvette part id: "${id}"`);
  return part;
};

export const tryGetPart = (id: string): PartDef | undefined => PART_BY_ID.get(id);

export const partsByCategory = (category: PartCategory): PartDef[] =>
  PARTS.filter((part) => part.category === category);

export const partsByStyle = (style: DesignStyle): PartDef[] =>
  PARTS.filter((part) => part.style === style);

export const partsByTag = (tag: string): PartDef[] => PARTS.filter((part) => part.tags.includes(tag));

